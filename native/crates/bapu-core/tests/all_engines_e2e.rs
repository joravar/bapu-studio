    let bq_qr = driver_for(DbKind::Bigquery)
        .query(&bq_cfg, "SELECT country, users FROM metrics")
        .await
        .unwrap();
    assert_eq!(bq_qr.rows[0]["country"], serde_json::json!("US"));

    // 7. Databricks SQL
    let dbx_cfg = base_conn(DbKind::Databricks, Some(url.clone()), "main.default");
    let dbx_qr = driver_for(DbKind::Databricks)
        .query(&dbx_cfg, "SELECT catalog, tables FROM info")
        .await
        .unwrap();
    assert_eq!(dbx_qr.rows[0]["catalog"], serde_json::json!("main"));

    // 8. Elasticsearch (both SQL and JSON DSL + index/mapping schema!)
    let es_cfg = base_conn(DbKind::Elasticsearch, Some(url.clone()), "logs-2026");
    let es_drv = driver_for(DbKind::Elasticsearch);
    assert!(es_drv.test_connection(&es_cfg).await.is_ok());
    let es_sql = es_drv.query(&es_cfg, "SELECT host, latency_ms FROM logs").await.unwrap();
    assert_eq!(es_sql.rows[0]["host"], serde_json::json!("edge-01"));
    let es_dsl = es_drv.query(&es_cfg, r#"{"query":{"match_all":{}}}"#).await.unwrap();
    assert_eq!(es_dsl.rows[0]["service"], serde_json::json!("api"));
    let es_schema = es_drv.get_schema(&es_cfg).await.unwrap();
    assert_eq!(es_schema[0].name, "logs-2026");

