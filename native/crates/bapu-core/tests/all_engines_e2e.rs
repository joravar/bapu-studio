    assert_eq!(tr_qr.rows[0]["region"], serde_json::json!("NA"));

    // 3. Turso / libSQL
    let ls_cfg = base_conn(DbKind::Libsql, Some(url.clone()), "main");
    let ls_qr = driver_for(DbKind::Libsql)
        .query(&ls_cfg, "SELECT id, edge_region FROM nodes")
        .await
        .unwrap();
    assert_eq!(ls_qr.rows[0]["edge_region"], serde_json::json!("iad"));

    // 4. QuestDB
    let q_cfg = base_conn(DbKind::Questdb, Some(url.clone()), "qdb");
